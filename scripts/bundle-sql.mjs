// Concatenate migrations + seeds into supabase/setup.sql for a one-paste
// setup in the Supabase SQL Editor. Run: npm run db:bundle
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "supabase");
const parts = ["migrations", "seed"].flatMap((dir) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((f) => `-- >>> ${dir}/${f}\n${readFileSync(join(root, dir, f), "utf8")}`),
);
writeFileSync(
  join(root, "setup.sql"),
  `-- GENERATED by scripts/bundle-sql.mjs — do not edit. Run once on a fresh project.\n\n${parts.join("\n\n")}`,
);
console.log(`Wrote supabase/setup.sql (${parts.length} files)`);
